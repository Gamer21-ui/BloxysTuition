// Joins every migration plus the seed into supabase/setup.sql so the whole database can be
// created by pasting ONE file into the Supabase SQL editor.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const dir = "supabase/migrations";
const parts = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort().map((f) => `-- ===== ${f} =====\n` + readFileSync(`${dir}/${f}`, "utf8"));
parts.push("-- ===== seed.sql =====\n" + readFileSync("supabase/seed.sql", "utf8"));
writeFileSync("supabase/setup.sql", "-- GENERATED by `npm run sql:bundle`. Paste into Supabase > SQL Editor > Run.\n\n" + parts.join("\n\n"));
console.log("wrote supabase/setup.sql");
