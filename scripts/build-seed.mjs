// O Level first, then AS & A Level (Accounting is O Level only). AS/A chapters carry their own notes.
const COURSES = [...O_COURSES, ...aEconomics, ...aBusiness, ...aCS];

// lesson notes per part, keyed by course slug then chapter number (array in part order)
const NOTES = { "o-accounting": notesAccounting, "o-business": notesBusiness, "o-economics": notesEconomics, "o-computer-science": notesCS };

// extra questions + improved explanations, keyed by course slug then chapter number
const EXTRA = { "o-accounting": accounting, "o-business": business, "o-economics": economics, "o-computer-science": computerScience };

// fairer prompts/options (no "pick the longest answer" pattern), keyed by course:chapter:index
// Past-paper Duel banks (exam-style MCQs with an answering guide), by course slug then chapter number.
export const PAPERS = { ...papersOCs };
// chapters whose duels open straight away (already taught)
const DUEL_OPEN = ["o-computer-science:3", "o-computer-science:4"];
export const REWRITES = { ...rewritesOCs, ...rewritesAsCs, ...rewritesACs, ...rewritesOAcc, ...rewritesOBus, ...rewritesOEco, ...rewritesAEco, ...rewritesABus };

// timed practice per course. Accounting & Economics match the real Paper 1 (2027 syllabus);
// Business & CS have no multiple-choice paper, so they get a mixed topic test instead.
const EXAMS = {
  "o-accounting": { title: "Paper 1 practice (40 questions, 1h 30m)", count: 40, secs: 5400, xp: 150 },
  "o-economics": { title: "Paper 1 practice (40 questions, 1h)", count: 40, secs: 3600, xp: 150 },
  "o-business": { title: "Mixed topic test (25 questions, 30m)", count: 25, secs: 1800, xp: 100 },
  "o-computer-science": { title: "Mixed topic test (25 questions, 30m)", count: 25, secs: 1800, xp: 100 },
  // 9708 Paper 1 (AS) and Paper 3 (A Level) are both 30 MCQs. Business and CS have no MCQ paper.
  "as-economics": { title: "Paper 1 practice (30 questions, 1h)", count: 30, secs: 3600, xp: 150 },
  "a-economics": { title: "Paper 3 practice (30 questions, 1h 15m)", count: 30, secs: 4500, xp: 175 },
  "as-business": { title: "Mixed topic test (25 questions, 30m)", count: 25, secs: 1800, xp: 100 },
  "a-business": { title: "Mixed topic test (25 questions, 30m)", count: 25, secs: 1800, xp: 125 },
  "as-computer-science": { title: "Mixed topic test (25 questions, 30m)", count: 25, secs: 1800, xp: 100 },
  "a-computer-science": { title: "Mixed topic test (25 questions, 30m)", count: 25, secs: 1800, xp: 125 },
};

const uid = (key) => {
  const h = createHash("sha1").update("funnybloxy:" + key).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (s) => (s === null || s === undefined ? "null" : "'" + String(s).replace(/'/g, "''") + "'");
const j = (o) => q(JSON.stringify(o)) + "::jsonb";

// deterministic shuffle so the correct answer isn't always option A
function shuffle(arr, seedKey) {
  let seed = parseInt(createHash("md5").update(seedKey).digest("hex").slice(0, 8), 16);
  const rnd = () => ((seed = (seed * 1664525 + 1013904223) % 4294967296) / 4294967296);
  const a = arr.map((v, i) => ({ v, i }));
  for (let i = a.length - 1; i > 0; i--) { const k = Math.floor(rnd() * (i + 1)); [a[i], a[k]] = [a[k], a[i]]; }
  return a;
}

const out = ["-- Generated by scripts/build-seed.mjs. Do not edit by hand.", "begin;"];
const partsOut = [];
const fixesOut = []; // question fixes only (paste-ready update)
const aOut = [];
const papersOut = []; // past-paper duel questions only (paste-ready update) // AS & A Level courses only // also written on their own so lesson notes can be updated separately
COURSES.forEach((c, ci) => {
  // AS/A statements are also collected on their own for the paste-ready update
  const emit = (line) => { out.push(line); if (c.tier !== "O") aOut.push(line); };
  const cid = uid("course:" + c.slug);
  emit(`insert into courses (id, slug, code, title, tier, exam_label, description, color, icon, sort) values (${q(cid)}, ${q(c.slug)}, ${q(c.code)}, ${q(c.title)}, ${q(c.tier)}, ${q(c.exam_label)}, ${q(c.description)}, ${q(c.color)}, ${q(c.icon)}, ${ci}) on conflict (id) do nothing;`);
  const sp = uid("speedrun:" + c.slug);
  emit(`insert into quizzes (id, course_id, chapter_id, title, kind, xp_reward, time_limit_sec, sort) values (${q(sp)}, ${q(cid)}, null, ${q(c.title + " Speedrun")}, 'speedrun', 60, 150, 999) on conflict (id) do nothing;`);
  const ex = EXAMS[c.slug];
  if (ex) emit(`insert into quizzes (id, course_id, chapter_id, title, kind, xp_reward, time_limit_sec, question_count, sort, status) values (${q(uid("exam:" + c.slug))}, ${q(cid)}, null, ${q(ex.title)}, 'exam', ${ex.xp}, ${ex.secs}, ${ex.count}, 1000, 'locked') on conflict (id) do nothing;`);
  emit(`insert into quizzes (id, course_id, chapter_id, title, kind, xp_reward, sort) values (${q(uid("review:" + c.slug))}, ${q(cid)}, null, ${q("Fix my mistakes")}, 'review', 0, 1001) on conflict (id) do nothing;`);
  c.chapters.forEach((ch, hi) => {
    const chid = uid(`chapter:${c.slug}:${ch.n}`);
    emit(`insert into chapters (id, course_id, number, title, sort) values (${q(chid)}, ${q(cid)}, ${q(ch.n)}, ${q(ch.t)}, ${hi}) on conflict (id) do nothing;`);
    ch.parts.forEach((p, pi) => {
      const [num, ...rest] = p.split(" ");
      const body = NOTES[c.slug]?.[ch.n]?.[pi] ?? ch.notes?.[pi] ?? null;
      // notes only fill parts that are still empty, so the tutor's own edits are never overwritten
      partsOut.push(`insert into parts (id, chapter_id, number, title, sort, body) values (${q(uid(`part:${c.slug}:${ch.n}:${pi}`))}, ${q(chid)}, ${q(num)}, ${q(rest.join(" "))}, ${pi}, ${q(body)}) on conflict (id) do update set body = coalesce(parts.body, excluded.body);`);
      emit(`insert into parts (id, chapter_id, number, title, sort, body) values (${q(uid(`part:${c.slug}:${ch.n}:${pi}`))}, ${q(chid)}, ${q(num)}, ${q(rest.join(" "))}, ${pi}, ${q(body)}) on conflict (id) do update set body = coalesce(parts.body, excluded.body);`);
    });
    if (ch.notes && ch.notes.length !== ch.parts.length) throw new Error(`notes count mismatch for ${c.slug} ${ch.n}`);
    const qzid = uid(`quiz:${c.slug}:${ch.n}`);
    emit(`insert into quizzes (id, course_id, chapter_id, title, kind, xp_reward, sort) values (${q(qzid)}, ${q(cid)}, ${q(chid)}, ${q(`Chapter ${ch.n} quiz`)}, 'quiz', 60, ${hi}) on conflict (id) do nothing;`);
    const extra = EXTRA[c.slug]?.[ch.n];
    if (extra && extra.fix.length !== ch.q.length) throw new Error(`fix count mismatch for ${c.slug} ${ch.n}`);
    const all = [...ch.q, ...(extra?.add || [])];
    all.forEach((item, qi) => {
      let [prompt, opts, correct, expl] = item;
      const fix = qi < ch.q.length ? extra?.fix[qi] : undefined;
      if (typeof fix === "string") expl = fix;
      else if (fix) { prompt = fix.p; expl = fix.e; }
      const rw = REWRITES[`${c.slug}:${ch.n}:${qi}`];
      if (rw) {
        if (rw.p) prompt = rw.p;
        if (rw.o) {
          if (rw.o.length !== opts.length) throw new Error(`rewrite option count mismatch for ${c.slug}:${ch.n}:${qi}`);
          opts = rw.o;
        }
      }
      const qid = uid(`q:${c.slug}:${ch.n}:${qi}`);
      const sh = shuffle(opts, qid);
      const newOpts = sh.map((x) => x.v);
      const newCorrect = sh.findIndex((x) => x.i === correct);
      // starter questions get their improved prompt/explanation; anything else about them is left as is
      emit(`insert into questions (id, course_id, chapter_id, quiz_id, prompt, options, explanation) values (${q(qid)}, ${q(cid)}, ${q(chid)}, ${q(qzid)}, ${q(prompt)}, ${j(newOpts)}, ${q(expl)}) on conflict (id) do update set prompt = excluded.prompt, explanation = excluded.explanation${rw?.o ? ", options = excluded.options" : ""};`);
      emit(`insert into question_keys (question_id, correct) values (${q(qid)}, ${newCorrect}) on conflict (question_id) do ${rw?.o ? "update set correct = excluded.correct" : "nothing"};`);
      if (rw) fixesOut.push(`update questions set prompt = ${q(prompt)}${rw.o ? `, options = ${j(newOpts)}` : ""} where id = ${q(qid)};`, ...(rw.o ? [`update question_keys set correct = ${newCorrect} where question_id = ${q(qid)};`] : []));
    });
    (PAPERS[c.slug]?.[ch.n] || []).forEach((pq, pi) => {
      if (pq.o.length !== 4 || !pq.g || !pq.e || !pq.r) throw new Error(`paper question incomplete: ${c.slug}:${ch.n}:${pi}`);
      if (/…|\.\.\./.test(pq.p)) throw new Error(`paper prompt must be a full question: ${c.slug}:${ch.n}:${pi}`);
      const qid = uid(`paper:${c.slug}:${ch.n}:${pi}`);
      const sh = shuffle(pq.o, qid);
      const opts = sh.map((x) => x.v), correct = sh.findIndex((x) => x.i === 0);
      const lines = [
        `insert into questions (id, course_id, chapter_id, quiz_id, prompt, options, explanation, battle_ok, source, ref, difficulty) values (${q(qid)}, ${q(cid)}, ${q(chid)}, null, ${q(pq.p)}, ${j(opts)}, ${q(pq.e)}, false, 'paper', ${q(pq.r)}, 2) on conflict (id) do update set prompt = excluded.prompt, options = excluded.options, explanation = excluded.explanation, ref = excluded.ref, source = 'paper', battle_ok = false;`,
        `insert into question_keys (question_id, correct, guide) values (${q(qid)}, ${correct}, ${q(pq.g)}) on conflict (question_id) do update set correct = excluded.correct, guide = excluded.guide;`,
      ];
      lines.forEach(emit); papersOut.push(...lines);
    });
    if (DUEL_OPEN.includes(`${c.slug}:${ch.n}`)) {
      const line = `update chapters set duel_open = true where id = ${q(chid)};`;
      emit(line); papersOut.push(line);
    }
  });
});
ACHIEVEMENTS.forEach((a) => {
  out.push(`insert into achievements (id, code, title, description, icon, rarity, xp_reward, criteria) values (${q(uid("ach:" + a.code))}, ${q(a.code)}, ${q(a.title)}, ${q(a.description)}, ${q(a.icon)}, ${q(a.rarity)}, ${a.xp}, ${j(a.criteria)}) on conflict (code) do nothing;`);
});
CHALLENGES.forEach((c, i) => {
  out.push(`insert into challenges (id, title, description, period, type, target, xp_reward, coin_reward) values (${q(uid("challenge:" + i))}, ${q(c.title)}, ${q(c.description)}, ${q(c.period)}, ${q(c.type)}, ${c.target}, ${c.xp}, ${c.coins}) on conflict (id) do nothing;`);
});
SHOP_ITEMS.forEach((it, i) => {
  out.push(`insert into shop_items (id, code, kind, name, description, price, rarity, min_level, data, sort, tutor_only) values (${q(uid("shop:" + it.kind + ":" + it.code))}, ${q(it.code)}, ${q(it.kind)}, ${q(it.name)}, ${q(it.description)}, ${it.price}, ${q(it.rarity)}, ${it.min_level || 1}, ${j(it.data || {})}, ${i}, ${it.tutor_only ? 'true' : 'false'}) on conflict (kind, code) do update set name = excluded.name, description = excluded.description, rarity = excluded.rarity, min_level = excluded.min_level, data = excluded.data, sort = excluded.sort, tutor_only = excluded.tutor_only;`);
});
out.push("commit;");
