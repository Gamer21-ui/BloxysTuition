writeFileSync(new URL("../supabase/seed-alevel.sql", import.meta.url),
  ["-- Generated by scripts/build-seed.mjs: AS & A Level courses, chapters, notes, quizzes and questions.", "begin;", ...aOut, "commit;"].join("\n") + "\n");
writeFileSync(new URL("../supabase/question-fixes.sql", import.meta.url),
  ["-- Generated by scripts/build-seed.mjs: fairer questions (balanced options, no trailing '…'). Safe to re-run.", "begin;", ...fixesOut, "commit;"].join("\n") + "\n");
writeFileSync(new URL("../supabase/paper-questions.sql", import.meta.url),
  ["-- Generated by scripts/build-seed.mjs: Past-paper Duel questions + answering guides. Safe to re-run.", "begin;", ...papersOut, "commit;"].join("\n") + "\n");
