// Regenerates the live_keys inserts in supabase/migrations/0020_live_lessons.sql from src/lib/viz.
// Usage: node scripts/viz-keys.mjs   (needs esbuild: npx esbuild is fine)
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
const dir = mkdtempSync(join(tmpdir(), "vizkeys-"));
execSync(`npx --yes esbuild src/lib/viz/index.ts --bundle --platform=node --format=esm --outfile=${dir}/viz.mjs --log-level=error`);
const { VIZZES } = await import(`${dir}/viz.mjs`);
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = [];
for (const v of VIZZES) v.steps.forEach((s, i) => { if (s.task) rows.push(`(${q(v.id)}, ${i}, ${q(JSON.stringify(s.task.answer))}::jsonb)`); });
const ids = VIZZES.map((v) => q(v.id)).join(", ");
const block = `-- @@KEYS@@ (generated by scripts/viz-keys.mjs, do not edit by hand)
delete from live_keys where viz in (${ids});
insert into live_keys(viz, step, answer) values
  ${rows.join(",\n  ")};
-- @@END-KEYS@@`;
const f = "supabase/migrations/0020_live_lessons.sql";
let sql = readFileSync(f, "utf8");
sql = sql.includes("@@END-KEYS@@") ? sql.replace(/-- @@KEYS@@[\s\S]*-- @@END-KEYS@@/, block) : sql.replace("-- @@KEYS@@", block);
writeFileSync(f, sql);
console.log(`${rows.length} keys for ${VIZZES.length} visualizations`);
